/** 제보를 데이터로 감싼 사용자 메시지 */
export function reportMessage(report: AgentReport): string {
  return [
    `패치 slug: ${report.slug}`,
    `이슈: ${report.issueUrl}`,
    `제목: ${report.title}`,
    '<report>',
    report.text,
    '</report>',
  ].join('\n');
}
